#include "kernel.h"

void vga_init(void) {}

void vga_putpixel(int x, int y, u8 col) {
    if (x < 0 || x >= (int)vga_width || y < 0 || y >= (int)vga_height) return;
    *(volatile u8*)(vga_fb_addr + (u32)y * vga_pitch + x) = col;
}

void vga_fill(u8 col) {
    u8 *fb = (u8*)(int)vga_fb_addr;
    u32 total = (u32)vga_height * vga_pitch;
    for (u32 i = 0; i < total; i++) fb[i] = col;
}

void vga_drawrect(int x, int y, int w, int h, u8 col) {
    for (int i = 0; i < w; i++) {
        vga_putpixel(x + i, y, col);
        vga_putpixel(x + i, y + h - 1, col);
    }
    for (int i = 0; i < h; i++) {
        vga_putpixel(x, y + i, col);
        vga_putpixel(x + w - 1, y + i, col);
    }
}

void vga_fillrect(int x, int y, int w, int h, u8 col) {
    if (x < 0) { w += x; x = 0; }
    if (y < 0) { h += y; y = 0; }
    if (x + w > (int)vga_width) w = vga_width - x;
    if (y + h > (int)vga_height) h = vga_height - y;
    if (w <= 0 || h <= 0) return;
    u8 *fb = (u8*)(int)vga_fb_addr;
    for (int j = 0; j < h; j++)
        for (int i = 0; i < w; i++)
            fb[(u32)(y + j) * vga_pitch + x + i] = col;
}

void vga_drawcircle(int cx, int cy, int r, u8 col) {
    for (int y = -r; y <= r; y++)
        for (int x = -r; x <= r; x++)
            if (x * x + y * y <= r * r)
                vga_putpixel(cx + x, cy + y, col);
}



static u8 font_simple[256][8];

void vga_drawchar(int x, int y, u8 c, u8 fg, u8 bg) {
    if (c < 32 || c > 254) c = '.';
    int idx = c - 32;
    for (int row = 0; row < 8; row++) {
        u8 bits = font_simple[idx][row];
        for (int col = 0; col < 8; col++) {
            vga_putpixel(x + col, y + row, (bits & (0x80 >> col)) ? fg : bg);
        }
    }
}

void vga_drawstring(int x, int y, const char *s, u8 fg, u8 bg) {
    while (*s) {
        vga_drawchar(x, y, *s, fg, bg);
        x += 9;
        if (x + 9 > (int)vga_width) { x = 0; y += 10; }
        s++;
    }
}

